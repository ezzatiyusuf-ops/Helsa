export async function seedCategoryTaxonomy({ dryRun = false }: { dryRun?: boolean } = {}) {
  if (dryRun || !process.env.DATABASE_URL) {
    console.log(`dry-run — ${ROWS.length} ردیف آماده برای درج (فقط ردیف‌های غایب نوشته می‌شوند)`);
    return { inserted: 0, planned: ROWS.length };
  }

  // فهرست موجود از دیتابیس (نه از فایل seed) تا روی دیتابیس خالی هم کامل کار کند
  const existingRows = await db.select({ slug: categories.slug }).from(categories);
  const existing = new Set(existingRows.map((r) => r.slug));
  const toInsert = ROWS.filter((r) => !existing.has(r.slug));
  if (toInsert.length === 0) {
    console.log(`✓ همهٔ ${ROWS.length} دسته از قبل موجود بودند — تغییری لازم نبود`);
    return { inserted: 0, planned: 0 };
  }

  // هم‌گام‌سازی سکانس id (seed پروژه شناسه‌ها را صریح درج می‌کند و سکانس عقب می‌ماند)
  await db.execute(
    sql`SELECT setval(pg_get_serial_sequence('categories', 'id'), COALESCE((SELECT max(id) FROM categories), 1))`,
  );

  const inserted = await db
    .insert(categories)
    .values(toInsert)
    .onConflictDoNothing({ target: categories.slug })
    .returning({ slug: categories.slug });
  // اتصال محصولات به رکورد دستهٔ خودشان (فقط جاهای خالی؛ هیچ محصولی جابه‌جا نمی‌شود)
  await db.execute(sql`
    UPDATE products p SET category_id = c.id
      FROM categories c
     WHERE c.slug = p.category AND p.category_id IS DISTINCT FROM c.id
  `);
  const [{ count }] = await db.select({ count: sql`count(*)::int` }).from(categories);
  console.log(`✓ ${inserted.length} دستهٔ تازه درج شد — مجموع categories: ${count}`);
  return { inserted: inserted.length, planned: toInsert.length };
}

/* اجرای مستقیم (بدون top-level await تا در tsx/CJS هم کار کند) */
if (process.argv[1]?.endsWith("seed-category-taxonomy.ts")) {
  seedCategoryTaxonomy({ dryRun: process.argv.includes("--dry-run") })
    .then(() => process.exit(0))
    .catch((e) => {
      console.error("خطا در seed تاکسونومی:", e?.message ?? e);
      process.exit(1);
    });
}
