import { chromium } from "playwright";
const b = await chromium.launch();
const m = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const p = await m.newPage();
await p.goto("http://localhost:3101/products", { waitUntil: "networkidle" });
const acc = p.getByRole("button", { name: "پذیرش همه" });
if (await acc.count()) await acc.first().click();
await p.waitForTimeout(400);
await p.getByRole("button", { name: /^فیلتر/ }).click();
await p.waitForTimeout(700);
await p.screenshot({ path: "/home/user/products-qa/filter-sheet-390.png" });
const d = await b.newContext({ viewport: { width: 1440, height: 950 } });
const dp = await d.newPage();
await dp.goto("http://localhost:3101/products", { waitUntil: "networkidle" });
if (await dp.getByRole("button", { name: "پذیرش همه" }).count()) await dp.getByRole("button", { name: "پذیرش همه" }).first().click();
await dp.waitForTimeout(400);
await dp.locator("aside").screenshot({ path: "/home/user/products-qa/sidebar-1440.png" }).catch(async () => { await dp.screenshot({ path: "/home/user/products-qa/sidebar-1440.png" }); });
await b.close();
console.log("ok");
