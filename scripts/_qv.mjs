import { chromium } from "playwright";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 950 } });
const p = await ctx.newPage();
await p.goto("http://localhost:3101/products", { waitUntil: "networkidle" });
const acc = p.getByRole("button", { name: "پذیرش همه" });
if (await acc.count()) await acc.first().click();
await p.waitForTimeout(300);
await p.locator("article.cat-card").first().hover();
await p.getByRole("button", { name: "نمای سریع" }).first().click();
await p.waitForTimeout(700);
await p.screenshot({ path: "/home/user/products-qa/quickview-1440.png" });
const m = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const mp = await m.newPage();
await mp.goto("http://localhost:3101/products", { waitUntil: "networkidle" });
if (await mp.getByRole("button", { name: "پذیرش همه" }).count()) await mp.getByRole("button", { name: "پذیرش همه" }).first().click();
await mp.waitForTimeout(300);
await mp.getByRole("button", { name: "نمای سریع" }).first().click();
await mp.waitForTimeout(700);
await mp.screenshot({ path: "/home/user/products-qa/quickview-390.png" });
await mp.getByRole("button", { name: "فیلتر محصولات" }).count().catch(()=>{});
await b.close();
console.log("ok");
